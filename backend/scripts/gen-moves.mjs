// Regenerates shared/src/moves.ts from Pokémon Showdown's Dex for every move in the pool.
// Run from backend/ after `npm install`:  node scripts/gen-moves.mjs
// (PS_PATH may point at another build of the `pokemon-showdown` package.)
import { createRequire } from 'node:module';
import fs from 'node:fs';
const require = createRequire(import.meta.url);
const { Dex } = require(process.env.PS_PATH || 'pokemon-showdown');
const pool = fs.readFileSync(new URL('../../shared/src/pool.ts', import.meta.url), 'utf8');
const names = new Set(['Struggle']);
for (const m of pool.matchAll(/moves:\[([^\]]*)\]/g)) for (const n of m[1].matchAll(/'([^']+)'/g)) names.add(n[1]);
// Descriptions live in Showdown's text tables, not on the move objects.
const text = Dex.loadTextData().Moves;
const out = {};
for (const name of [...names].sort()) {
  const mv = Dex.forGen(9).moves.get(name);
  if (!mv.exists) throw new Error(`Unknown move ${name}`);
  out[mv.id] = { name: mv.name, type: mv.type, category: mv.category, power: mv.basePower, accuracy: mv.accuracy === true ? 0 : mv.accuracy, priority: mv.priority, contact: !!mv.flags.contact, spread: ['allAdjacentFoes', 'allAdjacent', 'all', 'foeSide', 'allySide'].includes(mv.target), self: mv.target === 'self' || mv.target === 'allySide', status: mv.status ?? '', powder: !!mv.flags.powder, typeImmunity: mv.category !== 'Status' || mv.ignoreImmunity === false, desc: text[mv.id]?.shortDesc || text[mv.id]?.desc || '' };
}
const body = `// GENERATED by backend/scripts/gen-moves.mjs from Pokémon Showdown's Dex (MIT). Do not edit by hand.
import type { TypeName } from './pool.js';
export type MoveInfo = { name: string; type: TypeName; category: 'Physical' | 'Special' | 'Status'; power: number; /** 0 = never misses */ accuracy: number; priority: number; /** Makes contact (punches, bites, tackles) */ contact: boolean; /** Hits the whole field or a side */ spread: boolean; /** Targets the user or its side */ self: boolean; /** Major status it inflicts, if any */ status: string; /** Powder move (Grass types are immune) */ powder: boolean; /** Type immunities apply (all damaging moves, plus Thunder Wave-style status moves) */ typeImmunity: boolean; desc: string };
export const MOVES: Record<string, MoveInfo> = ${JSON.stringify(out, null, 1)};
export const moveId = (name: string) => name.toLowerCase().replace(/[^a-z0-9]/g, '');
export const moveInfo = (nameOrId: string): MoveInfo | null => MOVES[moveId(nameOrId)] ?? null;
`;
fs.writeFileSync(new URL('../../shared/src/moves.ts', import.meta.url), body);
console.log(`wrote ${Object.keys(out).length} moves`);

// Type chart: damageTaken codes per defending type (0 neutral, 1 weak, 2 resist, 3 immune), plus the
// condition immunities Showdown stores alongside them (brn, par, psn, tox, powder, sandstorm, ...).
const chart = {};
for (const name of Dex.forGen(9).types.names()) chart[name] = Dex.forGen(9).types.get(name).damageTaken;
fs.writeFileSync(new URL('../../shared/src/typechart.ts', import.meta.url), `// GENERATED by backend/scripts/gen-moves.mjs from Pokémon Showdown's Dex (MIT). Do not edit by hand.
import type { TypeName } from './pool.js';
/** damageTaken[defendingType][attackingTypeOrCondition]: 0 neutral, 1 weak (x2), 2 resist (x0.5), 3 immune. */
export const TYPE_CHART: Record<string, Record<string, number>> = ${JSON.stringify(chart, null, 1)};

/** Damage multiplier of an attacking type against a defender's types (Stellar is neutral). */
export function typeMultiplier(attack: TypeName, defender: readonly TypeName[]): number {
  let m = 1;
  for (const d of defender) {
    const code = TYPE_CHART[d]?.[attack] ?? 0;
    m *= code === 1 ? 2 : code === 2 ? 0.5 : code === 3 ? 0 : 1;
  }
  return m;
}
/** True when one of the defender's types is immune to a condition (brn, par, psn, tox, powder). */
export const conditionImmune = (cond: string, defender: readonly TypeName[]) => defender.some(d => TYPE_CHART[d]?.[cond] === 3);
`);
console.log(`wrote type chart (${Object.keys(chart).length} types)`);
